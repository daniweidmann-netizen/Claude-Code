// Mini-Markdown → HTML (nur die oben beschriebenen Elemente)
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const inline = (s) => esc(s)
  .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
  .replace(/\[(.+?)\]\(((?:https:\/\/|\/)[^)\s]+)\)/g, (_, t, u) => (u.startsWith('/')
    ? `<a href="${u}">${t}</a>`
    : `<a href="${u}" target="_blank" rel="noopener">${t}</a>`));

export function guideHtml(md) {
  const out = [];
  let list = null;
  const close = () => { if (list) { out.push(`</${list}>`); list = null; } };
  for (const raw of md.trim().split('\n')) {
    const line = raw.trim();
    if (!line) { close(); continue; }
    let m;
    if ((m = line.match(/^(#{2,3}) (.+)$/))) { close(); out.push(`<h${m[1].length}>${inline(m[2])}</h${m[1].length}>`); continue; }
    if ((m = line.match(/^- (.+)$/))) { if (list !== 'ul') { close(); out.push('<ul>'); list = 'ul'; } out.push(`<li>${inline(m[1])}</li>`); continue; }
    if ((m = line.match(/^(\d+)\. (.+)$/))) { if (list !== 'ol') { close(); out.push(m[1] === '1' ? '<ol>' : `<ol start="${m[1]}">`); list = 'ol'; } out.push(`<li>${inline(m[2])}</li>`); continue; }
    close(); out.push(`<p>${inline(line)}</p>`);
  }
  close();
  return out.join('\n');
}
